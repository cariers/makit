use crate::{MachineContext, Outcome};

/// 单个状态的输入处理与转换钩子。
///
/// 状态实现自行检查输入并返回 [`Outcome`]，区分已处理与未处理。
/// 返回未处理前不得修改领域数据；输入检查应在实际修改前完成。
/// 进入和退出钩子用于保证能够完成的状态维护，不返回错误或事件。
/// 该契约不提供 panic 捕获、数据回滚或外部副作用撤销。
pub trait State<M>
where
    Self: Sized,
    M: MachineContext,
{
    /// 处理本次输入，返回已处理的事件及转换，或未处理。
    ///
    /// 实现必须先检查输入是否能够处理，再修改当前状态和上下文。
    /// 返回 [`Outcome::Unhandled`] 时，必须保持调用本方法时的状态与上下文，
    /// 不得推进子机、消耗随机进度、写入领域事件或产生外部领域副作用。
    /// 驱动不自动回滚已发生的修改，也不自动要求父机转发或重试未处理的输入。
    ///
    /// 返回 [`Outcome::Handled`] 表示本次输入已经处理，可以修改状态与上下文。
    /// 底层受检操作的前提由实现保证，不能在部分修改后返回未处理。
    /// 当前状态的局部数据可以直接修改；正式切换状态应通过 [`crate::Transition::To`]
    /// 表达，不应直接替换 `self` 后返回 [`crate::Transition::Stay`] 绕过转换钩子。
    ///
    /// 已处理结果携带 [`crate::Transition::Stay`] 时不执行转换钩子；
    /// 携带 [`crate::Transition::To`] 时由驱动负责应用状态转换。
    /// 未处理结果不携带事件或转换，因此不执行转换钩子。
    ///
    /// [`crate::Machine`] 每次派发会先调用幂等的 [`crate::Machine::init`]。
    /// 若此次派发实际完成了初始化，未处理结果不会撤销进入本方法前已经完成的初始化。
    fn advance(&mut self, ctx: &mut M, input: &M::Input<'_>) -> Outcome<Self, M::Event>;

    /// 执行进入当前状态时保证能够完成的维护。
    ///
    /// 首次初始化以及切换到该状态时调用。普通机器可显式调用幂等的 [`crate::Machine::init`]，
    /// 每次派发也会先调用该方法，确保输入处理前已完成初始化。
    /// 严格机器由未初始化阶段的 `init` 完成初始化。
    /// 默认实现不执行任何操作。
    fn handle_entry_action(&mut self, _ctx: &mut M) {}

    /// 执行退出当前状态时保证能够完成的维护。
    ///
    /// 仅在推进要求切换状态时调用，此时能够看到本次推进对旧状态和上下文的修改。
    /// 保持当前状态或直接丢弃机器时不调用。
    /// 默认实现不执行任何操作。
    fn handle_exit_action(&mut self, _ctx: &mut M) {}
}
