//! 规则配置、整手状态与逐座状态的变体扩展契约。

/// 定义通用上下文之外的规则与两个作用域的状态。
///
/// 关联类型由调用者显式构造，没有专属数据的作用域可以使用 `()`。
/// 本 trait 不要求 `Default`、`Clone` 或 `Debug`，也不提供隐式初始化或流程钩子。
pub trait Variant {
    /// 当前一手采用的规则配置。
    type Rule;

    /// 当前一手共享的变体状态，例如跨座位准备信息。
    type Context;

    /// 随座位加入建立的专属状态，例如个人限制或变体持牌区。
    type SeatContext;
}
